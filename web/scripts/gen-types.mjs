// Generates src/lib/data.gen.ts from the ETL's JSON Schema (data/schema/*.json).
// Run after `wtbr schema`: pnpm gen:types
import { compile } from "json-schema-to-typescript";
import { readFileSync, readdirSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const dir = join(import.meta.dirname, "../../data/schema");

// Pydantic titles every property, which would become one alias type per field
// (and `Date` would shadow the global). Keep titles only on models.
function stripPropertyTitles(node) {
  if (Array.isArray(node)) return node.forEach(stripPropertyTitles);
  if (!node || typeof node !== "object") return;
  for (const prop of Object.values(node.properties ?? {})) delete prop.title;
  // Draft 2020 tuples (prefixItems) -> draft 7 tuples, which the compiler understands.
  if (node.prefixItems) {
    node.items = node.prefixItems;
    delete node.prefixItems;
  }
  for (const value of Object.values(node)) stripPropertyTitles(value);
}

const parts = ["/* Generated by scripts/gen-types.mjs from data/schema. Do not edit. */\n"];
const seen = new Set();
for (const file of readdirSync(dir).filter((f) => f.endsWith(".json")).sort()) {
  const schema = JSON.parse(readFileSync(join(dir, file), "utf8"));
  stripPropertyTitles(schema);
  const ts = await compile(schema, schema.title, { bannerComment: "", additionalProperties: false });
  // Shared definitions (Ranks, Sight, …) appear in several schemas; keep the first copy.
  for (const block of ts.split(/\n(?=export )/)) {
    const name = block.match(/^export (?:interface|type) (\w+)/)?.[1];
    if (name && seen.has(name)) continue;
    if (name) seen.add(name);
    parts.push(block.trim() + "\n");
  }
}
writeFileSync(join(import.meta.dirname, "../src/lib/data.gen.ts"), parts.join("\n"));
console.log(`wrote ${seen.size} types`);
